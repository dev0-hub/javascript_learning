export function translate(language, key) {
  const value = translations[language]?.[key];
  if (value === undefined) {
    if (import.meta.env?.DEV) console.warn(`Missing "${language}" translation: ${key}`);
    return translations.en[key] ?? key;
  }
  return value;
}
